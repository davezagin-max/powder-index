import { contourLines, smoothPath, tileableTerrain } from "@/lib/topo";

const TILE = 520;
const LEVELS = Array.from({ length: 13 }, (_, i) => -1.5 + i * 0.25);

// Computed once, at build time: this is a server component on a static page.
const contours = contourLines(tileableTerrain(TILE), { width: TILE, height: TILE, cell: 26 }, LEVELS);
const regular = contours
  .filter((_, index) => index % 4 !== 2)
  .flatMap((contour) => contour.lines.map(smoothPath))
  .join("");
const index = contours
  .filter((_, i) => i % 4 === 2)
  .flatMap((contour) => contour.lines.map(smoothPath))
  .join("");

/**
 * Faint topographic contour lines behind the whole page. They are generated by
 * marching squares over a height field that tiles exactly, with every fourth line
 * drawn heavier the way index contours are on a real topo map. Purely decorative.
 */
export function TopoBackground() {
  return (
    <svg aria-hidden className="pointer-events-none fixed inset-0 -z-10 h-full w-full">
      <defs>
        <pattern id="topo" width={TILE} height={TILE} patternUnits="userSpaceOnUse">
          <path d={regular} fill="none" stroke="var(--topo)" strokeWidth={1} />
          <path d={index} fill="none" stroke="var(--topo)" strokeWidth={1.8} />
        </pattern>
      </defs>
      <rect width="100%" height="100%" fill="url(#topo)" />
    </svg>
  );
}
